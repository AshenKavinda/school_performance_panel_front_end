// ── Role accent colours ───────────────────────────────────────────────────────
const ROLE_ACCENT = {
  ADMIN:             { header: 'bg-red-600',     badge: 'bg-red-100 text-red-700' },
  APPLICATION_ADMIN: { header: 'bg-purple-600',  badge: 'bg-purple-100 text-purple-700' },
  MANAGER:           { header: 'bg-blue-600',    badge: 'bg-blue-100 text-blue-700' },
  OPERATOR:          { header: 'bg-teal-600',    badge: 'bg-teal-100 text-teal-700' },
  TEACHER:           { header: 'bg-orange-600',  badge: 'bg-orange-100 text-orange-700' },
  STUDENT:           { header: 'bg-emerald-600', badge: 'bg-emerald-100 text-emerald-700' },
  GUEST:             { header: 'bg-gray-600',    badge: 'bg-gray-100 text-gray-700' },
};

const ROLE_LABELS = {
  ADMIN:             'Platform Admin',
  APPLICATION_ADMIN: 'School Admin',
  MANAGER:           'Manager',
  OPERATOR:          'Operator',
  TEACHER:           'Teacher',
  STUDENT:           'Student',
  GUEST:             'Guest',
};

// ── DashboardLayout ───────────────────────────────────────────────────────────
const DashboardLayout = ({ children, title }) => {
  const { user, logout } = useAuth();
  const navigate = useNavigate();
  const location = useLocation();
  const [sidebarOpen, setSidebarOpen] = useState(false);

  const handleLogout = useCallback(async () => {
    await logout();
    navigate('/login', { replace: true });
  }, [logout, navigate]);

  const role     = user?.role ?? 'GUEST';
  const accent   = ROLE_ACCENT[role] ?? ROLE_ACCENT.GUEST;
  const navItems = NAV_CONFIG[role] ?? [];

  const closeSidebar = () => setSidebarOpen(false);

  return (
    <div className="flex h-screen bg-gray-100 overflow-hidden">
      {/* ── Mobile overlay ─────────────────────────────── */}
      {sidebarOpen && (
        <div
          className="fixed inset-0 bg-black/50 z-20 lg:hidden"
          onClick={closeSidebar}
        />
      )}

      {/* ── Sidebar ────────────────────────────────────── */}
      <aside
        className={`
          fixed lg:static inset-y-0 left-0 z-30
          w-64 flex flex-col
          bg-gray-900 text-gray-100
          transform transition-transform duration-300 ease-in-out
          ${sidebarOpen ? 'translate-x-0' : '-translate-x-full lg:translate-x-0'}
        `}
      >
        {/* Brand header */}
        <div className={`flex items-center gap-3 px-5 py-[18px] ${accent.header} flex-shrink-0`}>
          <div className="flex items-center justify-center w-8 h-8 bg-white/20 rounded-lg flex-shrink-0">
            <svg className="w-5 h-5 text-white" fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2}
                d="M12 14l9-5-9-5-9 5 9 5z" />
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2}
                d="M12 14l6.16-3.422A12.083 12.083 0 0121 21H3a12.083 12.083 0 012.84-10.422L12 14z" />
            </svg>
          </div>
          <div className="min-w-0">
            <p className="text-sm font-bold text-white leading-tight">School Panel</p>
            <p className="text-xs text-white/70 truncate">{ROLE_LABELS[role] ?? role}</p>
          </div>
        </div>

        {/* Navigation */}
        <nav className="flex-1 overflow-y-auto py-3 px-3 space-y-0.5">
          {navItems.map((item) => {
            const isActive =
              location.pathname === item.path ||
              (item.path !== '/' && location.pathname.startsWith(item.path + '/'));
            return (
              <Link
                key={item.path}
                to={item.path}
                onClick={closeSidebar}
                className={`
                  flex items-center gap-3 px-3 py-2.5 rounded-xl text-sm font-medium transition
                  ${isActive
                    ? `${accent.header} text-white shadow-sm`
                    : 'text-gray-400 hover:bg-white/5 hover:text-white'
                  }
                `}
              >
                <span className="flex-shrink-0">
                  {ICONS[item.icon] ?? ICONS.home}
                </span>
                <span className="truncate">{item.label}</span>
              </Link>
            );
          })}
        </nav>

        {/* User footer */}
        <div className="border-t border-gray-800 p-3 flex-shrink-0">
          <div className="flex items-center gap-3 px-2 pb-2">
            <div className={`w-9 h-9 rounded-full ${accent.header} flex items-center justify-center flex-shrink-0`}>
              <span className="text-white text-sm font-bold">
                {user?.username?.[0]?.toUpperCase() ?? 'U'}
              </span>
            </div>
            <div className="min-w-0 flex-1">
              <p className="text-sm font-medium text-white truncate">{user?.username ?? 'User'}</p>
              <p className="text-xs text-gray-400 truncate">{user?.email ?? ''}</p>
            </div>
          </div>
          <button
            onClick={handleLogout}
            className="w-full flex items-center gap-2 px-3 py-2 text-sm text-gray-400 hover:text-white hover:bg-white/5 rounded-lg transition"
          >
            <svg className="w-4 h-4 flex-shrink-0" fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2}
                d="M17 16l4-4m0 0l-4-4m4 4H7m6 4v1a3 3 0 01-3 3H6a3 3 0 01-3-3V7a3 3 0 013-3h4a3 3 0 013 3v1" />
            </svg>
            Sign out
          </button>
        </div>
      </aside>

      {/* ── Main content area ───────────────────────────── */}
      <div className="flex-1 flex flex-col overflow-hidden min-w-0">
        {/* Top bar */}
        <header className="bg-white border-b border-gray-200 px-4 sm:px-6 h-[60px] flex items-center justify-between flex-shrink-0 gap-4">
          <div className="flex items-center gap-3 min-w-0">
            <button
              onClick={() => setSidebarOpen((v) => !v)}
              className="lg:hidden p-2 text-gray-500 hover:text-gray-700 hover:bg-gray-100 rounded-lg transition flex-shrink-0"
              aria-label="Toggle sidebar"
            >
              <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M4 6h16M4 12h16M4 18h16" />
              </svg>
            </button>
            <h1 className="text-base sm:text-lg font-semibold text-gray-800 truncate">
              {title ?? 'Dashboard'}
            </h1>
          </div>

          <div className="flex items-center gap-2 flex-shrink-0">
            <span className={`hidden sm:inline-flex items-center px-2.5 py-1 rounded-full text-xs font-medium ${accent.badge}`}>
              {ROLE_LABELS[role] ?? role}
            </span>
            <div className={`w-8 h-8 rounded-full ${accent.header} flex items-center justify-center text-white text-sm font-bold`}>
              {user?.username?.[0]?.toUpperCase() ?? 'U'}
            </div>
          </div>
        </header>

        {/* Page content */}
        <main className="flex-1 overflow-y-auto p-4 sm:p-6">
          {children}
        </main>
      </div>
    </div>
  );
};

export default DashboardLayout;
